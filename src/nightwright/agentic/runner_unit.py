"""`nw queue install | uninstall` (SPEC-0483): the queue runner as the systemd user unit
`nw-runner.service`, the supervisor that restarts it after a crash.

- The unit runs `nw queue run` in the foreground with `Restart=always`. A start limit
  (`StartLimitBurst` starts in `StartLimitIntervalSec`) ends a crash loop; the unit then fails
  and `OnFailure=` starts `nw-runner-failed.service`, which runs `nw queue unit-failed` (one
  queue-wide escalation).
- Credentials are not in the unit: the runner resolves `agentic.credentials` itself
  (`credentials.py`, `pass show`). The unit carries what `pass`/gpg need: a PATH (the
  installing shell's, minus virtualenv dirs, plus /usr/bin and /bin) and `GNUPGHOME` /
  `PASSWORD_STORE_DIR` when the installing shell sets them.
- `KillMode=process`: a stop or restart signals the runner only. Persona runs live in their
  own sessions and are adopted by the next runner (SPEC-0225/0229); the default
  `control-group` would kill them with it.
- While the unit file is installed, `nw queue run --detach`, `nw queue stop` and `nw queue
  restart` act through `systemctl --user` (`detach_runner` / `stop_runner` delegate), and a
  hand-started foreground `nw queue run` refuses while the unit is active. The unit's own
  process carries `NW_RUNNER_UNIT`, and its code-change re-exec is an exec of the same pid,
  which systemd keeps supervising."""
from __future__ import annotations

import os
import time
from pathlib import Path

from .dashboard import lifecycle as LC

UNIT_NAME = "nw-runner"
FAILED_UNIT_NAME = "nw-runner-failed"
UNIT_ENV = "NW_RUNNER_UNIT"                 # set in the unit: "this process is the unit's"
DIR_ENV = "NW_SYSTEMD_USER_DIR"             # tests: where the user unit files live
RESTART_SEC = 10
START_LIMIT_INTERVAL_S = 900                # 5 starts in 15 min: a crash loop, not a blip
START_LIMIT_BURST = 5
TIMEOUT_STOP_S = 120                        # SPEC-0229's 30 s stop bound plus the drain
START_WAIT_S = 30
ACTIVE_STATES = ("active", "activating", "reloading", "deactivating")
PASSTHROUGH_ENV = ("GNUPGHOME", "PASSWORD_STORE_DIR")   # captured at install when set
BASE_PATH = ("/usr/local/bin", "/usr/bin", "/bin")


def unit_dir() -> Path:
    d = os.environ.get(DIR_ENV)
    return Path(d) if d else LC.unit_dir()


def unit_path(name=UNIT_NAME) -> Path:
    return unit_dir() / f"{LC.unit_name(name)}.service"


def service(name=UNIT_NAME) -> str:
    return f"{LC.unit_name(name)}.service"


def installed() -> bool:
    """The unit file exists (no systemctl call): the switch for every delegation."""
    try:
        return unit_path().is_file()
    except (OSError, ValueError):
        return False


def in_unit() -> bool:
    return bool(os.environ.get(UNIT_ENV))


def unit_path_env(path_value: str | None) -> str:
    """The unit's PATH: the installing shell's entries minus virtualenv / worktree `.venv`
    dirs (`uv run` puts one first), then /usr/local/bin, /usr/bin and /bin when missing."""
    out = []
    for d in (path_value or "").split(os.pathsep):
        if not d or d in out or "/.venv/" in d + "/" or d.endswith("/.venv/bin"):
            continue
        if os.environ.get("VIRTUAL_ENV") and d.startswith(os.environ["VIRTUAL_ENV"]):
            continue
        out.append(d)
    out += [d for d in BASE_PATH if d not in out]
    return os.pathsep.join(out)


def unit_env(environ=None) -> dict:
    """`Environment=` of the unit: PATH, the `NW_*` dir overrides (SPEC-0427's rule) and the
    `pass`/gpg locations the installing shell sets. Never a credential."""
    environ = os.environ if environ is None else environ
    env = {"PATH": unit_path_env(environ.get("PATH"))}
    env.update(LC.env_overrides())
    for k in PASSTHROUGH_ENV:
        if environ.get(k):
            env[k] = environ[k]
    return env


def render_unit(*, nw_bin, env=None, name=UNIT_NAME) -> str:
    envs = [f"Environment={LC._q(f'{k}={v}')}" for k, v in sorted((env or {}).items())]
    n = LC.unit_name(name)
    lines = [
        "# Generated by `nw queue install` (SPEC-0483). Re-run it to change; "
        "`nw queue uninstall` removes it.",
        "[Unit]",
        "Description=nightwright queue runner (nw queue run)",
        f"StartLimitIntervalSec={START_LIMIT_INTERVAL_S}",
        f"StartLimitBurst={START_LIMIT_BURST}",
        f"OnFailure={service(FAILED_UNIT_NAME)}",
        "",
        "[Service]",
        "Type=simple",
        f"ExecStart={' '.join(LC._q(a) for a in (nw_bin, 'queue', 'run'))}",
        *envs,
        "Environment=PYTHONUNBUFFERED=1",
        f"Environment={UNIT_ENV}={n}.service",
        "Restart=always",
        f"RestartSec={RESTART_SEC}",
        "KillMode=process",
        f"TimeoutStopSec={TIMEOUT_STOP_S}",
        "StandardOutput=journal",
        "StandardError=journal",
        f"SyslogIdentifier={n}",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
    ]
    return "\n".join(lines)


def render_failed_unit(*, nw_bin, env=None) -> str:
    envs = [f"Environment={LC._q(f'{k}={v}')}" for k, v in sorted((env or {}).items())]
    lines = [
        "# Generated by `nw queue install` (SPEC-0483): started by nw-runner.service's "
        "OnFailure= when systemd gives up restarting the runner.",
        "[Unit]",
        "Description=nightwright queue runner gave up: escalate (nw queue unit-failed)",
        "",
        "[Service]",
        "Type=oneshot",
        f"ExecStart={' '.join(LC._q(a) for a in (nw_bin, 'queue', 'unit-failed', '--unit', service()))}",
        *envs,
        "Environment=PYTHONUNBUFFERED=1",
        "StandardOutput=journal",
        "StandardError=journal",
        f"SyslogIdentifier={FAILED_UNIT_NAME}",
        "",
    ]
    return "\n".join(lines)


def install_commands(*, restart=False) -> list[list[str]]:
    out = [["systemctl", "--user", "daemon-reload"],
           ["systemctl", "--user", "enable", "--now", service()]]
    if restart:
        out.append(["systemctl", "--user", "restart", service()])
    return out


def uninstall_commands() -> list[list[str]]:
    return [["systemctl", "--user", "disable", "--now", service()],
            ["systemctl", "--user", "reset-failed", service()],
            ["rm", "-f", str(unit_path()), str(unit_path(FAILED_UNIT_NAME))],
            ["systemctl", "--user", "daemon-reload"]]


def systemctl(args, run=None, timeout=LC.SYSTEMCTL_TIMEOUT_S):
    """`systemctl --user <args>` → CompletedProcess, or None (no systemctl / user bus, hang)."""
    import subprocess
    run = run or subprocess.run
    try:
        return run(["systemctl", "--user", *args], capture_output=True, text=True,
                   timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None


def show(run=None) -> dict | None:
    return LC.systemctl_show(UNIT_NAME, run)


def active(run=None) -> bool:
    s = show(run)
    return bool(s) and s.get("ActiveState") in ACTIVE_STATES


def _fail_text(p) -> str:
    if p is None:
        return "systemctl --user is not reachable"
    return ((p.stderr or p.stdout or "").strip().splitlines() or [f"exit {p.returncode}"])[-1]


def foreground_refusal(run=None) -> str | None:
    """Why a hand-started foreground `nw queue run` must not run: the unit is installed and
    active and this process is not the unit's. None otherwise."""
    if in_unit() or not installed() or not active(run):
        return None
    return (f"{service()} supervises the queue runner (installed at {unit_path()}) and is "
            "active; a second runner would only fight it for the lease. Use `nw queue stop`, "
            "`nw queue restart` or `systemctl --user restart nw-runner.service`, and read its "
            "log with `journalctl --user -u nw-runner.service -f`.")


def start(cfg, *, run=None, timeout_s=START_WAIT_S, clock=time.monotonic,
          sleep=time.sleep) -> dict:
    """`systemctl --user start nw-runner.service`, then wait until a runner holds the lease.
    `{pid, log, unit}`; ValueError when systemctl fails or no lease within `timeout_s`."""
    from . import lease as L
    p = systemctl(["start", service()], run=run, timeout=max(LC.SYSTEMCTL_TIMEOUT_S, 30))
    if p is None or p.returncode != 0:
        raise ValueError(f"systemctl --user start {service()} failed: {_fail_text(p)}")
    end = clock() + timeout_s
    while True:
        info = L.read_lease(cfg) or {}
        if L.is_held(cfg) and info.get("pid"):
            return {"pid": info["pid"], "log": f"journalctl --user -u {service()}",
                    "unit": service()}
        if clock() >= end:
            raise ValueError(f"{service()} started but no runner took the lease within "
                             f"{timeout_s:g}s; see journalctl --user -u {service()} -n 50")
        sleep(0.2)


def stop(*, run=None) -> None:
    """`systemctl --user stop --no-block nw-runner.service` (the caller waits on the lease)."""
    p = systemctl(["stop", "--no-block", service()], run=run)
    if p is None or p.returncode != 0:
        raise ValueError(f"systemctl --user stop {service()} failed: {_fail_text(p)}")


def escalate_failed(cfg, *, unit=None, run=None) -> dict | None:
    """`nw queue unit-failed` (the OnFailure hook): one queue-wide escalation while none is
    open (`kind: runner_unit_failed`). Returns the record, else None."""
    from . import escalations as ESC
    from .queue import journal
    unit = unit or service()
    s = show(run) or {}
    facts = [f"unit: {unit}", f"result: {s.get('Result') or '?'}",
             f"restarts: {s.get('NRestarts') or '?'}",
             f"last exit status: {s.get('ExecMainStatus') or '?'}",
             f"log: journalctl --user -u {unit} -n 100"]
    journal(cfg, "runner_unit_failed", unit=unit, result=s.get("Result"),
            n_restarts=s.get("NRestarts"), exit_status=s.get("ExecMainStatus"))
    for rec in ESC.list_all(cfg, "open"):
        if rec.get("kind") == "runner_unit_failed":
            return None
    plan = ESC.plan_escalate(
        cfg, None, frm="conductor", kind="runner_unit_failed", facts=facts,
        question=(f"systemd stopped restarting the queue runner: {unit} crashed "
                  f"{START_LIMIT_BURST} times within {START_LIMIT_INTERVAL_S // 60} minutes "
                  "and is failed. Nothing runs until it is started again."),
        options=(f"read the log (journalctl --user -u {unit} -n 100), fix the cause, then "
                 f"systemctl --user reset-failed {unit} && systemctl --user start {unit}",
                 "leave the runner stopped"))
    return ESC.apply_escalate(cfg, plan)
