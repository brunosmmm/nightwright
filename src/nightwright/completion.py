def _cfg_from_ctx(ctx) -> dict:
    """Prefer ctx.obj (Config dict) when present; otherwise load_config(). Soft-fail
    callers wrap this."""
    c = ctx
    while c is not None:
        if isinstance(getattr(c, "obj", None), dict) and "config_dir" in c.obj:
            return c.obj
        c = c.parent
    return load_config()


def _prefix_filter(values, incomplete: str):
    inc = incomplete or ""
    return [v for v in values if str(v).startswith(inc)]


def _clip_help(text, maxlen: int = 72) -> str:
    """Single-line help for CompletionItem; word-boundary trim (SPEC-0040)."""
    s = " ".join(str(text or "").split())
    if len(s) <= maxlen:
        return s
    cut = s[: maxlen - 1].rsplit(" ", 1)[0] or s[: maxlen - 1]
    return cut + "…"


def _items(values, incomplete: str, *, helps=None) -> list[CompletionItem]:
    helps = helps or {}
    out = []
    for v in _prefix_filter(values, incomplete):
        key = str(v)
        h = helps.get(key)
        out.append(CompletionItem(key, help=_clip_help(h) if h else None))
    return out


def _soft(fn):
    """Wrap a completer so any exception becomes []."""
    def wrapper(ctx, param, incomplete):
        try:
            return fn(ctx, param, incomplete)
        except Exception:
            return []
    wrapper.__name__ = getattr(fn, "__name__", "completer")
    wrapper.__doc__ = getattr(fn, "__doc__", None)
    return wrapper


