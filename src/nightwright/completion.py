def iter_cli_params(cmd=None, path=()):
    """Yield (path_tuple, command, param) for every Argument/Option under `cmd` (default: root cli)."""
    if cmd is None:
        from .cli import cli as cmd
    if isinstance(cmd, click.Group):
        for name, sub in sorted(cmd.commands.items()):
            yield from iter_cli_params(sub, path + (name,))
    for param in cmd.params:
        yield path, cmd, param


def _param_key(path, param):
    return f"{' '.join(path) if path else '(root)'}:{param.name}"


def _is_string_param(param) -> bool:
    """Plain-string value (multiple / nargs=-1 included); File, UUID, Tuple etc. are skipped."""
    if isinstance(param, click.Option) and param.is_flag:
        return False
    return isinstance(param.type, click.types.StringParamType)


def has_completer(param) -> bool:
    """True when `param` needs no further completer: a user-supplied `shell_complete`
    (Click stores it as `_custom_shell_complete`; `Parameter.shell_complete` is always a
    method, so testing it is vacuous), a flag, or a type Click completes/needs none for."""
    if getattr(param, "_custom_shell_complete", None) is not None:
        return True
    if isinstance(param, click.Option) and param.is_flag:
        return True
    return isinstance(param.type, (
        click.Path, click.Choice, click.types.IntParamType, click.types.FloatParamType,
        click.types.BoolParamType, click.DateTime,
    ))


def missing_required_shell_completes(cmd=None):
    """Return list of 'cmd.path:param' strings that violate REQUIRED_SHELL_COMPLETE_NAMES."""
    missing = []
    for path, _cmd, param in iter_cli_params(cmd):
        if param.name not in REQUIRED_SHELL_COMPLETE_NAMES or has_completer(param):
            continue
        key = _param_key(path, param)
        if key in UNCOMPLETED_EXEMPT:
            continue
        missing.append(key)
    return missing


